/// Width in points of `text` drawn at pixel size `px`.
pub fn text_width(text: &str, px: f32) -> f32 {
    let n = text.chars().count() as f32;
    if n == 0.0 {
        0.0
    } else {
        (n * ADVANCE - 1.0) * px
    }
}

/// Draw `text` with its top-left corner at `pos`, each font pixel `px` points wide.
pub fn draw(painter: &Painter, pos: Pos2, text: &str, px: f32, color: Color32) {
    let mut x = pos.x.round();
    let y = pos.y.round();
    for c in text.chars() {
        let rows = glyph(c);
        for (ry, bits) in rows.iter().enumerate() {
            // Merge horizontal runs into single rects to keep the draw count low.
            let mut cx = 0;
            while cx < 5 {
                if bits & (0b10000 >> cx) != 0 {
                    let start = cx;
                    while cx < 5 && bits & (0b10000 >> cx) != 0 {
                        cx += 1;
                    }
                    let r = Rect::from_min_size(
                        Pos2::new(x + start as f32 * px, y + ry as f32 * px),
                        Vec2::new((cx - start) as f32 * px, px),
                    );
                    painter.rect_filled(r, 0.0, color);
                } else {
                    cx += 1;
                }
            }
        }
        x += ADVANCE * px;
    }
}
